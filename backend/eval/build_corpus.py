#!/usr/bin/env python3
"""Rebuild the eval corpus from Python standard-library docstrings.

Each document is one public function or class: its name, signature and docstring,
exactly as `inspect.getdoc` returns them. Docstrings change a little between Python
versions, so the generated files are committed and this script is only needed to
regenerate them. The corpus is Python's own documentation (PSF license).

    python eval/build_corpus.py          # writes eval/corpus/*.txt
"""
import importlib
import inspect
import platform
import re
from pathlib import Path

NAMES = [
    "json.dumps", "json.loads", "csv.writer",
    "pathlib.Path.glob", "os.makedirs", "shutil.copytree", "shutil.rmtree", "shutil.which",
    "subprocess.run", "heapq.nlargest", "bisect.insort", "itertools.groupby", "itertools.chain",
    "functools.lru_cache", "functools.partial", "collections.Counter", "collections.defaultdict",
    "collections.deque", "datetime.timedelta", "re.sub", "re.findall", "zipfile.ZipFile",
    "random.sample", "statistics.median", "textwrap.wrap", "urllib.parse.urlparse",
    "base64.b64encode", "tempfile.NamedTemporaryFile", "glob.glob", "logging.basicConfig",
    "sqlite3.connect", "math.isclose", "secrets.token_hex",
]

OUT_DIR = Path(__file__).resolve().parent / "corpus"


def resolve(name: str):
    parts = name.split(".")
    for i in range(len(parts), 0, -1):
        try:
            obj = importlib.import_module(".".join(parts[:i]))
        except ImportError:
            continue
        for attr in parts[i:]:
            obj = getattr(obj, attr)
        return obj
    raise ImportError(name)


def render(name: str) -> str:
    obj = resolve(name)
    try:
        sig = re.sub(r" at 0x[0-9a-f]+", "", str(inspect.signature(obj)))
    except (TypeError, ValueError):
        sig = "(...)"
    doc = inspect.getdoc(obj) or ""
    return f"{name}{sig}\n\n{doc.strip()}\n"


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name in NAMES:
        (OUT_DIR / f"{name}.txt").write_text(render(name), encoding="utf-8")
    (OUT_DIR / "SOURCE.md").write_text(
        "Generated by `eval/build_corpus.py` from Python "
        f"{platform.python_version()} standard-library docstrings (PSF license).\n"
        f"{len(NAMES)} documents, one per function or class.\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(NAMES)} documents to {OUT_DIR}")


if __name__ == "__main__":
    main()
